/**
 * Writes supabase/seed/reference_data.sql — the company's master data without any demo
 * employees or transactions (company profile, directors, roles, departments, designations,
 * shifts, work centres, leave types, holidays). Use it for a clean production project.
 *   npx vite-node scripts/gen-reference-sql.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { generateSeed } from '../src/data/seed/index'
import type { AnyRow } from '../src/data/backend'

const TABLES = ['company_settings', 'directors', 'roles', 'departments', 'designations', 'shifts', 'work_centres', 'leave_types', 'holidays'] as const
// ids are left to the database; designations find their department by code
const SKIP = new Set(['id', 'head_employee_id', 'supervisor_id', 'demo_autopilot_through'])

function lit(v: unknown, col: string): string {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return String(v)
  if (Array.isArray(v)) {
    if (col === 'payroll' || col === 'attendance') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
    if (!v.length) return `'{}'`
    const t = v.every((x) => typeof x === 'number') ? 'int[]' : 'text[]'
    return `array[${v.map((x) => (typeof x === 'number' ? x : `'${String(x).replace(/'/g, "''")}'`)).join(', ')}]::${t}`
  }
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

const { tables } = await generateSeed(new Date())
const out: string[] = [
  '-- Melstar ERP — reference (master) data for a clean production database.',
  '-- Generated by scripts/gen-reference-sql.ts. Safe to re-run (ON CONFLICT DO NOTHING).',
  '-- Contains no demo employees or transactions. Apply after supabase/migrations/*.sql.',
  '',
  'begin;',
]
for (const t of TABLES) {
  const rows = (tables[t] ?? []) as AnyRow[]
  if (!rows.length) continue
  out.push('', `-- ${t} (${rows.length})`)
  const deptCode = new Map(((tables.departments ?? []) as AnyRow[]).map((d) => [d.id, String(d.code)]))
  for (const r of rows) {
    const cols = Object.keys(r).filter((c) => !SKIP.has(c) && c !== 'created_at' && c !== 'updated_at')
    if (t === 'designations') {
      const other = cols.filter((c) => c !== 'department_id')
      out.push(
        `insert into public.designations (${other.join(', ')}, department_id) select ${other.map((c) => lit(r[c], c)).join(', ')}, d.id from public.departments d where d.code = ${lit(deptCode.get(String(r.department_id)), 'code')} on conflict do nothing;`,
      )
      continue
    }
    const vals = cols.map((c) => (t === 'company_settings' && c === 'demo_autopilot' ? 'false' : lit(r[c], c)))
    out.push(`insert into public.${t} (${cols.join(', ')}) values (${vals.join(', ')}) on conflict do nothing;`)
  }
}
out.push(
  '',
  'commit;',
  '',
  '-- First administrator: create the user in Supabase → Authentication → Users (e-mail + password),',
  '-- then run (the login is linked to auth.users automatically by e-mail):',
  "-- insert into public.app_users (email, display_name, role_id, active)",
  "-- select 'admin@melstarmanufacturing.in', 'Melstar Admin', id, true from public.roles where key = 'super_admin';",
  '',
)
mkdirSync('supabase/seed', { recursive: true })
writeFileSync('supabase/seed/reference_data.sql', out.join('\n'))
console.log('wrote supabase/seed/reference_data.sql')
